"""Build and open the SQLite database from the TSV files in data/.

Source of truth is the TSVs (diffable, hand- and agent-editable):

  data/raw/wiki_items.tsv     id, name, category      (generated by tools/wiki_dump.js)
  data/items_curated.tsv      id, name, category, serving, confidence, basis
                              (non-empty fields override the wiki row)
  data/item_sources.tsv       item_id, source_type, source, notes
  data/dish_ingredients.tsv   learned from saves by `trtool learn`
  data/recipe_inputs.tsv      learned from saves by `trtool learn`

To add a new table: add it to schema.sql, add a TSV to data/, and add a
loader to TABLE_LOADERS below.
"""
import csv
import os
import sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
DEFAULT_DB = os.path.join(ROOT, "build", "trtool.db")
SCHEMA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "schema.sql")


def read_tsv(path, header=True):
    """Rows as dicts (header=True) or lists. Missing file -> []."""
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", newline="") as f:
        if header:
            return list(csv.DictReader(f, delimiter="\t"))
        return [r for r in csv.reader(f, delimiter="\t") if r]


def write_tsv(path, fieldnames, rows):
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, delimiter="\t",
                           lineterminator="\n", extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def _int(v):
    v = (v or "").strip()
    return int(v) if v.lstrip("-").isdigit() else None


def _none(v):
    v = (v or "").strip()
    return v or None


def load_items(con, data_dir):
    items = {}
    for r in read_tsv(os.path.join(data_dir, "raw", "wiki_items.tsv"), header=False):
        i = _int(r[0])
        if i is None:
            continue
        items[i] = {"id": i, "name": r[1] if len(r) > 1 else None,
                    "category": r[2] if len(r) > 2 else None, "serving": None,
                    "name_confidence": "wiki", "name_basis": "travellersrest.wiki.gg"}
    for r in read_tsv(os.path.join(data_dir, "items_curated.tsv")):
        i = _int(r.get("id"))
        if i is None:
            continue
        row = items.setdefault(i, {"id": i, "name": None, "category": None, "serving": None,
                                   "name_confidence": None, "name_basis": None})
        for src, dst in (("name", "name"), ("category", "category"), ("serving", "serving"),
                         ("confidence", "name_confidence"), ("basis", "name_basis")):
            if _none(r.get(src)):
                row[dst] = r[src].strip()
    con.executemany(
        "INSERT INTO items VALUES (:id,:name,:category,:serving,:name_confidence,:name_basis)",
        items.values())


def load_sources(con, data_dir):
    for r in read_tsv(os.path.join(data_dir, "item_sources.tsv")):
        if _int(r.get("item_id")) is not None and _none(r.get("source_type")):
            con.execute("INSERT INTO item_sources VALUES (?,?,?,?)",
                        (_int(r["item_id"]), r["source_type"].strip(),
                         _none(r.get("source")), _none(r.get("notes"))))


def load_dish_ingredients(con, data_dir):
    for r in read_tsv(os.path.join(data_dir, "dish_ingredients.tsv")):
        con.execute("INSERT OR REPLACE INTO dish_ingredients VALUES (?,?,?,?,?)",
                    (_int(r["dish_id"]), _int(r["ingredient_id"]),
                     _int(r.get("seen_count")) or 1, _none(r.get("first_seen")),
                     _none(r.get("last_seen"))))


def load_recipe_inputs(con, data_dir):
    for r in read_tsv(os.path.join(data_dir, "recipe_inputs.tsv")):
        con.execute("INSERT OR REPLACE INTO recipe_inputs VALUES (?,?,?,?,?,?)",
                    (_int(r["recipe_id"]), _int(r["output_id"]), _int(r["ingredient_id"]),
                     _int(r.get("amount")), _none(r.get("first_seen")),
                     _none(r.get("last_seen"))))


TABLE_LOADERS = [load_items, load_sources, load_dish_ingredients, load_recipe_inputs]


def build(db_path=DEFAULT_DB, data_dir=DATA):
    os.makedirs(os.path.dirname(db_path), exist_ok=True)
    if os.path.exists(db_path):
        os.remove(db_path)
    con = sqlite3.connect(db_path)
    with open(SCHEMA, encoding="utf-8") as f:
        con.executescript(f.read())
    for loader in TABLE_LOADERS:
        loader(con, data_dir)
    con.commit()
    return con


def connect(db_path=DEFAULT_DB, data_dir=DATA, rebuild=False):
    """Open the database, building it first if missing, stale or asked to."""
    stale = not os.path.exists(db_path)
    if not stale:
        built = os.path.getmtime(db_path)
        for dirpath, _, files in os.walk(data_dir):
            if any(os.path.getmtime(os.path.join(dirpath, f)) > built
                   for f in files if f.endswith(".tsv")):
                stale = True
                break
        if os.path.getmtime(SCHEMA) > built:
            stale = True
    if stale or rebuild:
        con = build(db_path, data_dir)
    else:
        con = sqlite3.connect(db_path)
    con.row_factory = sqlite3.Row
    return con


class Names:
    """Item-ID -> display name lookup, falling back to '#id'."""

    def __init__(self, con):
        self.rows = {r["id"]: dict(r) for r in con.execute("SELECT * FROM items")}

    def __call__(self, i):
        r = self.rows.get(i)
        if not r or not r["name"]:
            return "#%d" % i
        if r["name_confidence"] in ("guess", "set known"):
            return "%s? (#%d)" % (r["name"], i)
        return r["name"]

    def get(self, i):
        return self.rows.get(i, {})

    def category(self, i):
        return (self.rows.get(i) or {}).get("category")

    def is_drink(self, i):
        return self.category(i) == "Drinks"

    def on_tap(self, i):
        return (self.rows.get(i) or {}).get("serving") == "tap"
